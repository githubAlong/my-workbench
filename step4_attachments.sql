-- ============================================================================
--  第四步：附件表上云（attachments）
--
--  在 Supabase 后台 → SQL Editor → New query → 整段粘贴 → Run（可重复执行）
--  跑完看页面下方的自检表：一行，rls已开启 / 强制rls / anon无权限 都要是 true
--
--  ────────────────────────────────────────────────────────────────────────
--  【这一步解决什么】
--  以前上传的 Excel、课件、发票只存在「浏览器自己的仓库」里（localStorage）。
--  于是在电脑上导入的考勤表，用手机打开点「原表」是空的 —— 文件根本没离开过那台电脑。
--
--  这一步把附件也搬到 Postgres 上，跟考勤表一个账号保管。搬完之后：
--    · 电脑传的原表，手机上点「原表」就能下回来
--    · 换一台电脑登录同一个账号，附件跟着走
--
--  【为什么文件内容也塞进数据库，而不是用 Storage】
--  Supabase 有专门存文件的 Storage（对象存储），更"正规"。
--  但它要多两步：先建一个 bucket、再配一套 Storage 的访问策略 ——
--  这两步都得在同一个控制台里点，出错的地方就从一处变成三处。
--  而这一版的数据量很小（一个学期几十张考勤表，十几 MB），
--  直接存数据库字段完全吃得下，而且**只需要跑这一份 SQL**。
--  等哪天要存几百份大文件了，再换 Storage 也不迟 —— 那时只改上传下载两处代码。
--
--  【url 这一列为什么是 text 而不是 bytea】
--  前端存的本来就是 data URL（`data:application/vnd...;base64,UEsDBBQ...`），
--  <img src> 和 <a href> 直接就能认，不用转。
--  用 bytea 的话，前端每次都要在 base64 ↔ 二进制之间编解码，
--  多一层转换就多一层出错的机会。代价是 base64 比原文件大约 1/3，
--  换来的是前后端都不用碰二进制 —— 这个交换很值。
--
--  【为什么单行会有 2MB 也不怕】
--  Postgres 对大字段会自动做 TOAST —— 超长的文字被压缩后存到行外的附加表里，
--  主表那一行仍然很小，查询列表时不会因此变慢。
--  真正会变慢的是"一次把几十 MB 的 base64 全查回来"，
--  所以前端列表接口只查元数据、不查 url，要下载时才单独取那一个。
--  （代码在 js/localapi.js 的 /attachments 与 /attachments/:id/file）
-- ============================================================================


-- ============================================================================
--  一、附件表
-- ============================================================================
create table if not exists public.attachments (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users(id) on delete cascade,

  /* 这条附件挂在什么东西上：
       attendance —— 考勤表的原表（当初上传的 Excel）和现场照片
       material   —— 课件附件
       trip       —— 出差报销的发票 / 凭证
     这一版只有 attendance 会走云端，另外两类主表还没上云，请求会落回本机。
     留着 owner_type 这个字段，是为了将来它们上云时不用改表结构。 */
  owner_type  text not null default 'misc',

  /* 对应主表的 id。
     **故意不加外键**：考勤主表在 attendance_tables，课件和发票的主表各是各的，
     一条外键只能指向一张表。靠 owner_type + 下面那条索引 + RLS 就够了。 */
  owner_id    bigint not null default 0,

  name        text,                                -- 原始文件名，如「高一坐班表.xlsx」
  mime        text,                                -- 类型，如 application/vnd.openxml...
  size        bigint not null default 0,           -- 原始字节数（不是 base64 后的长度）

  /* path 现在固定是 'inline-<id>'，是早期留下的字段：
     那时设想过"文件放别处，这里存路径"。既然现在内容就在 url 里，
     这个字段只做占位。等换成 Storage 时，它会变成真正的对象路径。 */
  path        text,

  /* 文件本体：data URL，如 'data:application/vnd...;base64,UEsDBBQ...'
     可以为空 —— 早期从别处导进来的种子数据只有元数据、没有内容。 */
  url         text,

  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  deleted_at  timestamptz
);

/* 单文件 1.5MB 上限，让数据库自己兜住。
   前端也拦了一道，但前端拦得住"正常上传"，拦不住"绕过页面的脚本"、
   也拦不住将来某次改动忘了同步这个数。数据库这一条是最后的底线。

   【为什么用 not valid】
   加约束时会顺带检查已有数据。如果库里有历史遗留的超大行，直接加约束会失败，
   整个脚本就卡在这儿 —— 而用户根本看不懂 "violates check constraint" 是什么意思。
   not valid 表示"只对**以后**写入的行生效"，现有数据不动。
   这样这一步永远不会因为老数据失败，而新的写入照样被管住。 */
alter table public.attachments
  drop constraint if exists attachments_size_limit;
alter table public.attachments
  add constraint attachments_size_limit check (size <= 1572864) not valid;

/* 查附件永远带着"挂在哪儿"这个条件，索引就按这个顺序建。
   where deleted_at is null 让索引只覆盖还在用的行，回收站里的不占。 */
create index if not exists attachments_owner_idx
  on public.attachments (user_id, owner_type, owner_id, id)
  where deleted_at is null;


-- ============================================================================
--  二、RLS：只看自己的
-- ============================================================================
alter table public.attachments enable row level security;
alter table public.attachments force row level security;

drop policy if exists attachments_all_own on public.attachments;
create policy attachments_all_own on public.attachments
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);


-- ============================================================================
--  三、权限：先收回，再只给登录用户
--     （加策略不会收回授权，不 revoke 等于敞着 —— 前面几张表都踩过）
-- ============================================================================
revoke all on public.attachments from anon;
revoke all on public.attachments from public;

grant select, insert, update, delete on public.attachments to authenticated;


-- ============================================================================
--  四、updated_at 自动更新
--
--  这里**重新建一次** wb_touch_updated_at()，而不是假设第一步已经建过。
--  原因和第二步一样：用户可能只跑这一步，也可能在别处重建了库。
--  create or replace 是幂等的 —— 存在就覆盖，不存在就新建，两种情况都不会报错。
-- ============================================================================
create or replace function public.wb_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists attachments_touch on public.attachments;
create trigger attachments_touch
  before update on public.attachments
  for each row execute function public.wb_touch_updated_at();


-- ============================================================================
--  五、自检
--     期望：一行，rls已开启=t, 强制rls=t, anon无权限=t, 策略数=1
--     任何一项是 f，就是没跑成功 —— 把这一行截图发我。
-- ============================================================================
select
  c.relname                                                    as 表名,
  c.relrowsecurity                                             as rls已开启,
  c.relforcerowsecurity                                        as 强制rls,
  not has_table_privilege('anon', 'public.' || c.relname, 'select')      as anon无权限,
  has_table_privilege('authenticated', 'public.' || c.relname, 'select') as 登录用户可读,
  (select count(*) from pg_policies p
    where p.schemaname = 'public' and p.tablename = c.relname)  as 策略数
from pg_class c
join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public'
  and c.relname = 'attachments';
