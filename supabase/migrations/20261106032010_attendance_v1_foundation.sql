create table if not exists public.wb_user_data (
  user_id uuid primary key default auth.uid() references auth.users(id) on delete cascade,
  payload jsonb not null check (jsonb_typeof(payload) = 'object'),
  revision bigint not null default 1 check (revision > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.attendance_tables (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  grade text not null check (length(btrim(grade)) between 1 and 40),
  sheet_type text not null check (sheet_type in ('seat', 'research', 'class')),
  sheet_date date not null,
  name text not null default '考勤表',
  weekday text not null default '',
  periods text not null default '',
  month text not null default '',
  subject text not null default '',
  columns jsonb not null default '[]'::jsonb check (jsonb_typeof(columns) = 'array'),
  meta jsonb not null default '{}'::jsonb check (jsonb_typeof(meta) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create table if not exists public.attendance_rows (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  table_id bigint not null references public.attendance_tables(id) on delete restrict,
  teacher text not null check (length(btrim(teacher)) between 2 and 20),
  subject text not null check (length(btrim(subject)) between 1 and 20),
  data jsonb not null default '{}'::jsonb check (jsonb_typeof(data) = 'object'),
  sort integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create table if not exists public.attachments (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  owner_type text not null default 'misc',
  owner_id bigint not null,
  name text not null default '',
  mime text not null default '',
  size bigint not null default 0 check (size >= 0),
  path text not null default '',
  url text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

-- One active seat, research and class table per user/grade/day.
create unique index if not exists attendance_tables_daily_identity_uniq
  on public.attendance_tables (user_id, grade, sheet_date, sheet_type)
  where deleted_at is null;

create index if not exists attendance_tables_user_date_idx
  on public.attendance_tables (user_id, sheet_date desc, grade)
  where deleted_at is null;

create index if not exists attendance_rows_table_sort_idx
  on public.attendance_rows (table_id, sort, id)
  where deleted_at is null;

-- Exact duplicate name+subject records are rejected inside one active sheet.
create unique index if not exists attendance_rows_identity_uniq
  on public.attendance_rows (
    table_id,
    lower(btrim(teacher)),
    lower(btrim(subject))
  )
  where deleted_at is null;

create index if not exists attachments_owner_idx
  on public.attachments (user_id, owner_type, owner_id)
  where deleted_at is null;

