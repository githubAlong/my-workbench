create or replace function public.wb_save_user_data(
  p_payload jsonb,
  p_expected_revision bigint default 0
)
returns public.wb_user_data
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  saved public.wb_user_data;
begin
  if auth.uid() is null then
    raise exception 'WB_AUTH_REQUIRED' using errcode = '42501';
  end if;
  if jsonb_typeof(p_payload) <> 'object' then
    raise exception 'WB_INVALID_SNAPSHOT' using errcode = '22023';
  end if;

  insert into public.wb_user_data (user_id, payload, revision)
  values (auth.uid(), p_payload, 1)
  on conflict (user_id) do update
    set payload = excluded.payload,
        revision = public.wb_user_data.revision + 1,
        updated_at = now()
    where public.wb_user_data.revision = coalesce(p_expected_revision, 0)
  returning * into saved;

  if saved.user_id is null then
    raise exception 'WB_DATA_REVISION_CONFLICT' using errcode = '40001';
  end if;
  return saved;
end;
$$;

create or replace function public.wb_save_attendance_rows(
  p_table_id bigint,
  p_rows jsonb,
  p_mark_dirty boolean default true
)
returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_table public.attendance_tables;
  v_item jsonb;
  v_existing public.attendance_rows;
  v_ids jsonb := '[]'::jsonb;
  v_id_text text;
  v_teacher text;
  v_subject text;
  v_expected timestamptz;
  v_sort integer;
  v_new_id bigint;
  v_saved integer := 0;
begin
  if auth.uid() is null then
    raise exception 'WB_AUTH_REQUIRED' using errcode = '42501';
  end if;

  select * into v_table
  from public.attendance_tables
  where id = p_table_id
    and user_id = auth.uid()
    and deleted_at is null
  for update;

  if not found then
    raise exception 'WB_ATTENDANCE_TABLE_NOT_FOUND' using errcode = 'P0002';
  end if;
  if jsonb_typeof(coalesce(p_rows, '[]'::jsonb)) <> 'array' then
    raise exception 'WB_ATTENDANCE_ROWS_INVALID' using errcode = '22023';
  end if;

  select coalesce(max(sort), 0) into v_sort
  from public.attendance_rows
  where table_id = p_table_id and deleted_at is null;

  for v_item in select value from jsonb_array_elements(coalesce(p_rows, '[]'::jsonb))
  loop
    v_teacher := btrim(coalesce(v_item->>'teacher', ''));
    v_subject := btrim(coalesce(v_item->>'subject', ''));
    v_id_text := nullif(v_item->>'id', '');

    -- Blank editor rows remain local until the teacher fills name and subject.
    if v_teacher = '' or v_subject = '' then
      v_ids := v_ids || 'null'::jsonb;
      continue;
    end if;

    if v_id_text is not null then
      select * into v_existing
      from public.attendance_rows
      where id = v_id_text::bigint
        and table_id = p_table_id
        and user_id = auth.uid()
        and deleted_at is null
      for update;

      if not found then
        raise exception 'WB_ATTENDANCE_CONFLICT: row deleted by another client'
          using errcode = '40001';
      end if;

      v_expected := nullif(v_item->>'expected_updated_at', '')::timestamptz;
      if v_expected is not null and v_existing.updated_at <> v_expected then
        raise exception 'WB_ATTENDANCE_CONFLICT: row changed by another client'
          using errcode = '40001';
      end if;

      update public.attendance_rows
      set teacher = v_teacher,
          subject = v_subject,
          data = coalesce(v_item->'data', '{}'::jsonb)
      where id = v_existing.id
      returning id into v_new_id;
    else
      v_sort := v_sort + 1;
      insert into public.attendance_rows (
        user_id, table_id, teacher, subject, data, sort
      ) values (
        auth.uid(), p_table_id, v_teacher, v_subject,
        coalesce(v_item->'data', '{}'::jsonb), v_sort
      )
      returning id into v_new_id;
    end if;

    v_ids := v_ids || to_jsonb(v_new_id);
    v_saved := v_saved + 1;
  end loop;

  if p_mark_dirty
    and coalesce(v_table.meta->>'confirmed_at', '') <> ''
    and coalesce(v_table.meta->>'confirm_dirty', '0') <> '1'
  then
    update public.attendance_tables
    set meta = jsonb_set(coalesce(meta, '{}'::jsonb), '{confirm_dirty}', '1'::jsonb, true)
    where id = p_table_id;
  end if;

  return jsonb_build_object('ids', v_ids, 'saved', v_saved);
exception
  when unique_violation then
    raise exception 'WB_ATTENDANCE_DUPLICATE: same teacher and subject already exist'
      using errcode = '23505';
end;
$$;

create or replace function public.wb_rename_attendance_grade(
  p_old text,
  p_new text
)
returns integer
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_count integer;
begin
  if auth.uid() is null then
    raise exception 'WB_AUTH_REQUIRED' using errcode = '42501';
  end if;
  if btrim(coalesce(p_old, '')) = '' or btrim(coalesce(p_new, '')) = '' then
    raise exception 'WB_GRADE_NAME_REQUIRED' using errcode = '22023';
  end if;

  update public.attendance_tables
  set grade = btrim(p_new)
  where user_id = auth.uid()
    and grade = btrim(p_old)
    and deleted_at is null;
  get diagnostics v_count = row_count;
  return v_count;
exception
  when unique_violation then
    raise exception 'WB_GRADE_ALREADY_EXISTS' using errcode = '23505';
end;
$$;

create or replace function public.wb_delete_attendance_grade(
  p_grade text
)
returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_at timestamptz := now();
  v_tables integer;
  v_rows integer;
begin
  if auth.uid() is null then
    raise exception 'WB_AUTH_REQUIRED' using errcode = '42501';
  end if;

  with targets as (
    select id
    from public.attendance_tables
    where user_id = auth.uid()
      and grade = btrim(p_grade)
      and deleted_at is null
  ), deleted_rows as (
    update public.attendance_rows r
    set deleted_at = v_at
    from targets t
    where r.table_id = t.id
      and r.user_id = auth.uid()
      and r.deleted_at is null
    returning r.id
  )
  select count(*) into v_rows from deleted_rows;

  update public.attendance_tables
  set deleted_at = v_at
  where user_id = auth.uid()
    and grade = btrim(p_grade)
    and deleted_at is null;
  get diagnostics v_tables = row_count;

  return jsonb_build_object('tables', v_tables, 'rows', v_rows);
end;
$$;

