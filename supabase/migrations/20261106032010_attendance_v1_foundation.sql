create or replace function public.wb_attendance_row_owner_guard()
returns trigger
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
begin
  if not exists (
    select 1
    from public.attendance_tables t
    where t.id = new.table_id
      and t.user_id = new.user_id
      and t.user_id = auth.uid()
      and t.deleted_at is null
  ) then
    raise exception 'WB_ATTENDANCE_TABLE_FORBIDDEN'
      using errcode = '42501';
  end if;
  return new;
end;
$$;

