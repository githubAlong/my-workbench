-- 上课记录台账：独立数据表
-- 与旧 public.lessons 完全分离；不迁移旧表数据。
create table if not exists public.class_records (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  class_type text not null check (class_type in ('normal','i_substitute','substituted_for_me','swap')),
  subject text not null,
  class_name text,
  grade text,
  teacher text,
  class_time text,
  related_person text,
  amount numeric(12,2),
  pay_time text,
  pay_status text check (pay_status is null or pay_status in ('未支付','已支付')),
  remark text,
  class_month text check (class_month is null or class_month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

-- 支付状态允许手动输入任意文字，保留已有记录与相关人员字段。
alter table public.class_records drop constraint if exists class_records_pay_status_check;

create index if not exists class_records_user_month_idx
  on public.class_records (user_id, class_month, created_at desc);

alter table public.class_records enable row level security;
alter table public.class_records force row level security;

revoke all on public.class_records from anon;
revoke all on public.class_records from public;
grant select, insert, update, delete on public.class_records to authenticated;
grant usage, select on sequence public.class_records_id_seq to authenticated;

drop policy if exists class_records_select_own on public.class_records;
drop policy if exists class_records_insert_own on public.class_records;
drop policy if exists class_records_update_own on public.class_records;
drop policy if exists class_records_delete_own on public.class_records;

create policy class_records_select_own on public.class_records
  for select to authenticated using ((select auth.uid()) = user_id);
create policy class_records_insert_own on public.class_records
  for insert to authenticated with check ((select auth.uid()) = user_id);
create policy class_records_update_own on public.class_records
  for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
create policy class_records_delete_own on public.class_records
  for delete to authenticated using ((select auth.uid()) = user_id);

drop trigger if exists class_records_touch on public.class_records;
create trigger class_records_touch
  before update on public.class_records
  for each row execute function public.wb_touch_updated_at();

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (
       select 1 from pg_publication_tables
       where pubname = 'supabase_realtime'
         and schemaname = 'public'
         and tablename = 'class_records'
     ) then
    alter publication supabase_realtime add table public.class_records;
  end if;
end $$;
