-- ============================================================================
--  第一步（A 方案）：只做「课时」一张表的真云端
--
--  目标：先跑通最小闭环，验证思路对不对，再铺开到其它 28 张表。
--  跑通标准：手机上登录 → 看到课时 → 电脑上改一条 → 手机刷新能看到。
--
--  在 Supabase 后台 → SQL Editor → New query → 整段粘贴 → Run
--  可重复执行。
--
--  ────────────────────────────────────────────────────────────────────────
--  【跟之前那版 wb_sync 的区别】
--  之前：整库 JSON 存成一行，靠一把 sync_key 认人。那是「快照」，不是数据库。
--  现在：课时拆成真正的行和列，靠 Supabase Auth 登录后的 auth.uid() 认人。
--        每条记录带 user_id，RLS 保证你只看得到自己的行。
--
--  【安全模型】
--  1. 表开 RLS，策略一律 `auth.uid() = user_id`，且限定 to authenticated
--     —— 未登录的请求（anon）直接被拒，连一行都读不到。
--  2. user_id 的默认值设为 auth.uid()：客户端插入时不用（也不能）自己填，
--     伪造不了别人的身份。
--  3. revoke 掉 anon 的所有权限。Supabase 会给 public 新表自动授权，
--     「加策略不会收回授权」，不 revoke 就是敞着的。
-- ============================================================================

-- ---------- 课时表 ----------
-- 字段与前端 localdb.js 的 lessons 一一对应，一个不多一个不少，
-- 这样迁移脚本和前端都不用做字段改名映射。
create table if not exists public.lessons (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null default auth.uid() references auth.users(id) on delete cascade,

  date         date,            -- 上课日期
  period_no    int,             -- 第几节
  time_range   text,            -- 时间段（展示用，如 "07:40-08:25"）
  start_time   text,
  end_time     text,

  grade        text,            -- 年级
  class_name   text,            -- 班级
  subject      text,            -- 学科
  teacher      text,            -- 任课老师
  substitute   text,            -- 代课人
  sub_type     text,            -- normal / sub_in(替他人) / sub_out(他人替我) / swap(换课)
  sub_note     text,

  content      text,            -- 本节内容
  progress     text,            -- 进度
  next_content text,            -- 下节计划
  discipline   text,            -- 课堂纪律

  hours        numeric default 1,   -- 课时数
  remark       text,

  peer_name    text,            -- 对调/代课对象姓名
  peer_id      bigint,
  orig_teacher text,

  pay_hours    numeric,         -- 计费课时
  unit_price   numeric,         -- 单价
  pay_amount   numeric,         -- 金额
  settle_note  text,            -- 结算备注
  swap_from   text,
  swap_to      text,
  settled_at   timestamptz,     -- 已结算时间
  settle_key   text,

  -- 与前端一致的通用字段：软删除 + 时间戳
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  deleted_at   timestamptz
);

-- 常用查询：某天的课、某月的课（按月统计课时费）
create index if not exists lessons_user_date_idx
  on public.lessons (user_id, date desc);

-- ---------- 安全 ----------
alter table public.lessons enable row level security;
alter table public.lessons force  row level security;

-- 收回 Supabase 自动授予的权限（关键，光写 policy 挡不住）
revoke all on public.lessons from anon;
revoke all on public.lessons from public;

-- 只给已登录用户开放必要的四个动作
grant select, insert, update, delete on public.lessons to authenticated;

-- 连自增序列也要授权，否则 insert 会报 permission denied for sequence
grant usage, select on all sequences in schema public to authenticated;

-- ---------- 策略：只有本人能读写自己的行 ----------
drop policy if exists lessons_select_own on public.lessons;
drop policy if exists lessons_insert_own on public.lessons;
drop policy if exists lessons_update_own on public.lessons;
drop policy if exists lessons_delete_own on public.lessons;

create policy lessons_select_own on public.lessons
  for select to authenticated
  using ((select auth.uid()) = user_id);

create policy lessons_insert_own on public.lessons
  for insert to authenticated
  with check ((select auth.uid()) = user_id);

create policy lessons_update_own on public.lessons
  for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

create policy lessons_delete_own on public.lessons
  for delete to authenticated
  using ((select auth.uid()) = user_id);

-- ---------- updated_at 自动更新 ----------
create or replace function public.wb_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists lessons_touch on public.lessons;
create trigger lessons_touch
  before update on public.lessons
  for each row execute function public.wb_touch_updated_at();

-- ---------- 自检 ----------
-- 期望：rls已开启=t，强制RLS=t，anon无权限=t，策略数=4
select
  c.relname                                   as 表名,
  c.relrowsecurity                            as rls已开启,
  c.relforcerowsecurity                       as 强制rls,
  not has_table_privilege('anon', 'public.lessons', 'select') as anon无权限,
  has_table_privilege('authenticated', 'public.lessons', 'select') as 登录用户可读,
  (select count(*) from pg_policies p
    where p.schemaname='public' and p.tablename='lessons') as 策略数
from pg_class c
join pg_namespace n on n.oid = c.relnamespace
where n.nspname='public' and c.relname='lessons';
