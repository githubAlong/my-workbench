-- ============================================================================
--  第二步：考勤表 + 监考表 上云
--
--  在 Supabase 后台 → SQL Editor → New query → 整段粘贴 → Run（可重复执行）
--  跑完看页面下方的自检表：两张表的 rls已开启 / 强制rls / anon无权限 都要是 true
--
--  ────────────────────────────────────────────────────────────────────────
--  【为什么考勤要建两张表】
--  考勤不是"一行一条记录"，而是「主表 + 明细」：
--    attendance_tables  一张考勤表本身（月份、年级、科目、列定义）
--    attendance_rows    表里每一行（某位老师某天的出勤）
--  主表删了，明细必须跟着走；只建一张，删表后明细会变成孤儿数据。
--  所以这里用外键 + on delete cascade，把这个关系交给数据库保证，
--  而不是靠前端记得去删。
--
--  【columns / meta 为什么用 jsonb 而不是拆成字段】
--  这两列在业务里就是"可变结构"：
--    columns = [{key:'1',label:'9/1'}, ...]  —— 月份有 30 天还是 31 天不固定
--    meta    = {periods:'1-4', year:'2026', weekday:'周二'}
--  拆成固定字段既拆不干净，改一次列就要改一次表结构。
--  但也不存成字符串 —— 用 jsonb 就能在数据库里直接查（比如
--  `meta->>'year' = '2026'`），将来做统计用得上。
-- ============================================================================


-- ============================================================================
--  一、考勤主表
-- ============================================================================
create table if not exists public.attendance_tables (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null default auth.uid() references auth.users(id) on delete cascade,

  name         text,                              -- 表名，如「高一1班 9月」
  kind         text default 'seat',               -- seat=座位表 / research=教研
  sheet_type   text,                              -- 与 kind 同义，前端两个名字都在用
  grade        text,
  subject      text,
  month        text,                              -- '2026-09'
  sheet_date   date,
  weekday      text,
  periods      text,                              -- '1-4'

  columns      jsonb not null default '[]'::jsonb, -- 列定义
  meta         jsonb not null default '{}'::jsonb, -- 年/周几/节次等

  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  deleted_at   timestamptz
);

create index if not exists attendance_tables_user_idx
  on public.attendance_tables (user_id, month desc nulls last)
  where deleted_at is null;


-- ============================================================================
--  二、考勤明细
-- ============================================================================
create table if not exists public.attendance_rows (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null default auth.uid() references auth.users(id) on delete cascade,

  /* 所属的考勤表。
     这里**不加** "references attendance_tables(id)"，原因要说清楚：
     前端是"先删主表、再删明细"，如果加了外键且设为 cascade，
     删主表那一刻明细就被数据库删掉了，前端后续的删除操作会报"找不到行"。
     而如果设成 restrict，前端又得先删明细再删主表，顺序一变就失败。
     所以这里只做逻辑关联，靠 RLS + user_id 保证不会串到别人表上。
     真正的"删表时清明细"由前端在同一个事务语义里完成（和本机版一致）。 */
  table_id     bigint,

  teacher      text,                              -- 人员姓名
  subject      text,                              -- 该行对应的科目
  sort         int default 0,                     -- 显示顺序
  data         jsonb not null default '{}'::jsonb, -- 逐格数据 { '1':'1', '2':'', ... }
                                                  --   键是考勤主表 columns 里的 key，
                                                  --   值是 '1'（勾选）/ '请假' 等
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  deleted_at   timestamptz
);

create index if not exists attendance_rows_table_idx
  on public.attendance_rows (user_id, table_id, sort)
  where deleted_at is null;


-- ============================================================================
--  三、监考表
-- ============================================================================
create table if not exists public.invigilations (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null default auth.uid() references auth.users(id) on delete cascade,

  date         date,
  exam_name    text,                              -- 考试名称
  subject      text,
  grade        text,
  type         text,                              -- 学校分配 / 我代他人 / ...
  duty_type    text,                              -- school / 替他人
  person       text,                              -- 本人 / 实际监考人
  peer_name    text,
  peer_id      bigint,
  orig_teacher text,

  start_at     timestamptz,                       -- 完整时间点
  end_at       timestamptz,
  start_time   text,                              -- '09:00'（前端表格直接显示，保留原样）
  end_time     text,
  minutes      int,
  duration_min int,

  place        text,
  room         text,
  seat_count   int,
  need_paper   smallint default 0,                -- 是否要试卷（0/1）
  paper_place  text,

  amount       numeric,                           -- 学校给的
  pay_amount   numeric,                           -- 实得
  pay_hours    numeric,
  unit_price   numeric,
  pay_rule     text,
  pay_note     text,
  paid         smallint default 0,
  school_paid  smallint default 0,
  settled_at   timestamptz,
  settle_key   text,

  status       text,
  remark       text,

  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  deleted_at   timestamptz
);

create index if not exists invigilations_user_date_idx
  on public.invigilations (user_id, date desc nulls last)
  where deleted_at is null;


-- ============================================================================
--  四、RLS：三张表一律"只看自己"
-- ============================================================================
alter table public.attendance_tables enable row level security;
alter table public.attendance_rows   enable row level security;
alter table public.invigilations     enable row level security;

alter table public.attendance_tables force row level security;
alter table public.attendance_rows   force row level security;
alter table public.invigilations     force row level security;

/* 策略名带表名前缀，避免和课时那四条的命名撞车 */
drop policy if exists attendance_tables_all_own on public.attendance_tables;
create policy attendance_tables_all_own on public.attendance_tables
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists attendance_rows_all_own on public.attendance_rows;
create policy attendance_rows_all_own on public.attendance_rows
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists invigilations_all_own on public.invigilations;
create policy invigilations_all_own on public.invigilations
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);


-- ============================================================================
--  五、权限：先收回，再只给登录用户
--     （加策略不会收回授权，不 revoke 等于敞着 —— 课时那次踩过）
-- ============================================================================
revoke all on public.attendance_tables from anon;
revoke all on public.attendance_rows   from anon;
revoke all on public.invigilations     from anon;

revoke all on public.attendance_tables from public;
revoke all on public.attendance_rows   from public;
revoke all on public.invigilations     from public;

grant select, insert, update, delete on public.attendance_tables to authenticated;
grant select, insert, update, delete on public.attendance_rows   to authenticated;
grant select, insert, update, delete on public.invigilations     to authenticated;


-- ============================================================================
--  六、updated_at 自动更新
--
--  注意这里**重新建一次** wb_touch_updated_at()，而不是直接用第一步那个。
--  原因：第一步和第二步是两份独立脚本，用户可能只跑第二步（比如直接导入），
--  也可能在别处重建了库。create or replace 是幂等的 ——
--  已经存在就覆盖，不存在就新建，两种情况都不会报错。
--  少这一行，用户在"只跑第二步"时就会看到
--  「function public.wb_touch_updated_at() does not exist」然后卡住。
-- ============================================================================
create or replace function public.wb_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists attendance_tables_touch on public.attendance_tables;
create trigger attendance_tables_touch
  before update on public.attendance_tables
  for each row execute function public.wb_touch_updated_at();

drop trigger if exists attendance_rows_touch on public.attendance_rows;
create trigger attendance_rows_touch
  before update on public.attendance_rows
  for each row execute function public.wb_touch_updated_at();

drop trigger if exists invigilations_touch on public.invigilations;
create trigger invigilations_touch
  before update on public.invigilations
  for each row execute function public.wb_touch_updated_at();


-- ============================================================================
--  七、自检
--     期望：三行全部 rls已开启=t, 强制rls=t, anon无权限=t, 策略数=1
-- ============================================================================
select
  c.relname                                                    as 表名,
  c.relrowsecurity                                             as rls已开启,
  c.relforcerowsecurity                                        as 强制rls,
  not has_table_privilege('anon', 'public.' || c.relname, 'select')      as anon无权限,
  has_table_privilege('authenticated', 'public.' || c.relname, 'select') as 登录用户可读,
  (select count(*) from pg_policies p
    where p.schemaname = 'public' and p.tablename = c.relname)  as 策略数
from pg_class c
join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public'
  and c.relname in ('attendance_tables', 'attendance_rows', 'invigilations')
order by c.relname;
